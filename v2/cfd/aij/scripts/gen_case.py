"""Generate OpenFOAM (ESI v2306+) cases for the AIJ Case A benchmark (isolated 1:1:2 building).

Pure structured multi-block blockMesh (17 hex blocks around the building "hole"): the building is an
axis-aligned box, so a body-fitted hex mesh with controlled grading gives better quality (orthogonality,
no snapping/layer artefacts, exact edges) than snappyHexMesh, and it is trivially refined systematically
for the GCI study (every segment's cell count x f, same total expansion ratios).

Examples (from this folder):
  python gen_case.py --kind building --model realizableKE --level 1.0 --out E:/PINN/runs/aij/bld_rke_M
  python gen_case.py --kind empty2d  --model kOmegaSST   --inlet table --ground rough --out E:/PINN/runs/aij/hom_sst_table_rough

Conventions: x streamwise, y lateral, z up; origin at the building centre on the floor (same as the AIJ data).
"""
