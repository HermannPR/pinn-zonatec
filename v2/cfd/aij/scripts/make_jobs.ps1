<#
  Write queue jobs (contract E:\PINN\cola\README.md) for AIJ Case A cases already generated by make_cases.ps1.
  Replaces the retired run_queue.ps1: long runs go ONLY through the fail-safe queue.

  powershell -File make_jobs.ps1 -Cases bld_rke_M,bld_sst_M,bld_ske_M -Start 20 [-After 019_x]
  -> E:\PINN\cola\jobs\020_aij_bld_rke_M.json, 021_..., each depending on the previous one (sequential,
     so the 6-rank runs never overlap). Log: E:\PINN\logs\jobs\<id>.log ; state: E:\PINN\cola\state\<id>.*
#>
param([Parameter(Mandatory = $true)][string[]]$Cases, [int]$Start = 20, [string]$After = '',
      [int]$HangMinutes = 60, [int]$MaxAttempts = 3, [int]$MinFreeGb = 10)
if ($Cases.Count -eq 1 -and $Cases[0].Contains(',')) { $Cases = $Cases[0].Split(',') }
$py = 'E:\PINN\.venv\Scripts\python.exe'
$verify = 'E:\PINN\v2\cfd\aij\scripts\verify_aij.py'
$prev = $After
$n = $Start
foreach ($c in $Cases) {
    $case = "E:\PINN\runs\aij\$c"
    if (-not (Test-Path "$case\Allrun")) { Write-Warning "no Allrun in $case"; continue }
    $id = '{0:D3}_aij_{1}' -f $n, $c
    $job = [ordered]@{
        id           = $id
        fase         = 'F1 validacion AIJ'
        kind         = 'openfoam'
        case         = $case
        cmd          = 'bash ./Allrun'
        verify       = "& '$py' '$verify' '$case'; exit `$LASTEXITCODE"
        min_free_gb  = $MinFreeGb
        max_attempts = $MaxAttempts
        hang_minutes = $HangMinutes
        notify       = "AIJ Caso A: $c"
    }
    if ($prev) { $job.after = @($prev) }
    $job | ConvertTo-Json -Depth 4 | Out-File -Encoding utf8 "E:\PINN\cola\jobs\$id.json"
    "wrote $id"
    $prev = $id
    $n++
}
