"""Prepare a finished-but-oscillating steady case for a pseudo-time average continuation.

Steady RANS around the 1:1:2 building can settle into a limit cycle in iteration space (k-omega SST here:
period ~125 iterations, U range up to 0.25 U_H at one wake probe). Following common practice, the solution is
continued for N more iterations with fieldAverage (UMean, kMean) and the averaged fields are sampled at the
same points/lines as the instantaneous ones (sets named <name>Mean, fields renamed on read by post_aij --mean).

Usage: python add_mean_sampling.py <case> <extra_iterations>
Writes system/controlDict (functions extended, endTime = last + N) and Allrun.mean (resumable, parallel).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

case = Path(sys.argv[1])
extra = int(sys.argv[2])
meta = json.loads((case / "case.json").read_text())
cd = (case / "system" / "controlDict").read_text()
if "fieldAverageMean" in cd:
    print("already prepared")
    sys.exit(0)

times = [float(p.name) for p in (case / "processor0").iterdir() if re.fullmatch(r"[0-9.e+-]+", p.name) and p.name != "0"]
t0 = int(max(times))
t1 = t0 + extra


def block(name: str) -> str:
    i = cd.index(f"    {name}\n    {{")
    depth, j = 0, cd.index("{", i)
    while True:
        if cd[j] == "{":
            depth += 1
        elif cd[j] == "}":
            depth -= 1
            if depth == 0:
                return cd[i:j + 1]
        j += 1


new = []
for n in ("sampleExp", "sampleLines", "sampleProfiles"):
    b = block(n).replace(f"    {n}\n", f"    {n}Mean\n", 1)
    b = re.sub(r"fields\s+\(([^)]*)\);", lambda m: "fields          (" + " ".join(
        {"U": "UMean", "k": "kMean", "p": "pMean", "nut": "nutMean"}.get(f, f) for f in m.group(1).split()) + ");", b)
    new.append(b)
favg = f"""
    fieldAverageMean
    {{
        type            fieldAverage;
        libs            (fieldFunctionObjects);
        timeStart       {t0};
        writeControl    writeTime;
        fields
        (
            U {{ mean on; prime2Mean off; base iteration; }}
            k {{ mean on; prime2Mean off; base iteration; }}
            p {{ mean on; prime2Mean off; base iteration; }}
            nut {{ mean on; prime2Mean off; base iteration; }}
        );
    }}
"""
# the Mean sets must only be written at the end (after averaging): writeControl onEnd
new = [b.replace("writeControl    writeTime;", "writeControl    onEnd;") for b in new]
k = cd.rindex("}")
cd = cd[:k] + favg + "\n".join(new) + "\n" + cd[k:]
cd = re.sub(r"endTime\s+\d+;", f"endTime         {t1};", cd, count=1)
(case / "system" / "controlDict").write_text(cd, newline="\n")

np_ = meta["np"]
allrun = f"""#!/bin/bash
# pseudo-time average continuation {t0} -> {t1} (generated by add_mean_sampling.py); resumable
set -eo pipefail
cd "${{0%/*}}"
NP={np_}
rm -f DONE.mean FAILED.mean
trap 'echo "FAILED: line $LINENO" > FAILED.mean' ERR
run() {{ local log=$1; shift; echo "Running $*  -> $log"; "$@" 2>&1 | tee "$log"; ! grep -q "FOAM FATAL" "$log"; }}
if [ ! -f .mean.ok ]; then
    foamDictionary -entry endTime -set {t1} system/controlDict > /dev/null
    foamDictionary -entry writeInterval -set 200 system/controlDict > /dev/null
    # restart from {t0}: drop later incomplete times of a killed attempt (averaging restarts cleanly from t0)
    for d in processor*; do for t in $(ls -1 $d | grep -E '^[0-9.e+-]+$' | sort -g); do
        if awk "BEGIN{{exit !($t > {t0})}}"; then rm -rf "$d/$t"; fi; done; done
    rm -rf postProcessing/*Mean
    run log.simpleFoam.mean mpiexec -n $NP simpleFoam -parallel
    touch .mean.ok
fi
if [ ! -f .reconstructMean.ok ]; then
    run log.reconstructPar.mean reconstructPar -latestTime
    touch .reconstructMean.ok
fi
echo "OK $(date)" > DONE.mean
"""
(case / "Allrun.mean").write_text(allrun, newline="\n")
meta["mean_average"] = {"from": t0, "to": t1}
(case / "case.json").write_text(json.dumps(meta, indent=2))
print(f"prepared {case.name}: average {t0}->{t1}")
