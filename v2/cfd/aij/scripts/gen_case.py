B = 0.08
H = 0.16
KAPPA = 0.41
CMU = 0.09
Z0_AIJ = 1.125e-3 * H     # ground z0 specified by the AIJ organisers for Case A (Tominaga et al. 2004, Table 4) = 0.18 mm

# ---------------------------------------------------------------- geometry & base segments
# Domain (Tominaga et al. 2008 guideline): >= 5H lateral and above the building, >= 10H behind it.
X0, X3 = -(B / 2 + 5 * H), B / 2 + 12.5 * H      # -0.84 .. 2.04 m  (5H upstream of windward face, 12.5H behind)
Y0, Y3 = -(B / 2 + 5 * H), B / 2 + 5 * H          # +-0.84 m        (5H clearance each side)
ZT = H + 5 * H                                    # 0.96 m          (5H above the roof)
D0 = 0.002                                        # base (medium) cell size at building edges / ground [m]
# base cell counts (level f = 1): upstream, building (per half), downstream, lateral, 0..H (per half), above H
NBASE = dict(xu=35, bh=10, xd=60, yl=35, zh=15, za=38)


def solve_ratio(L: float, n: int, d0: float) -> float:
    """cell-to-cell ratio r with d0 * (r^n - 1)/(r - 1) = L"""
    if abs(n * d0 - L) < 1e-12:
        return 1.0
    lo, hi = (1.0 + 1e-9, 3.0) if n * d0 < L else (0.2, 1.0 - 1e-9)
    for _ in range(200):
        r = 0.5 * (lo + hi)
        s = d0 * (r ** n - 1) / (r - 1)
        if (s < L) == (n * d0 < L):
            lo = r
        else:
            hi = r
    return 0.5 * (lo + hi)


class Seg:
    """1-D segment: length L, base count n, first cell d0 at the 'fine' end; E = total expansion (last/first)."""

    def __init__(self, L, n, d0, fine="start", twosided=False):
        self.L, self.n0, self.fine, self.twosided = L, n, fine, twosided
        Lh = L / 2 if twosided else L
        self.r0 = solve_ratio(Lh, n, d0)
        self.E = self.r0 ** (n - 1)                    # growth from the fine end over one (half) segment

    def n(self, f):
        return max(2, int(round(self.n0 * f))) * (2 if self.twosided else 1)

    def grading(self, f):
        if self.twosided:
            return f"((0.5 0.5 {self.E:.6g}) (0.5 0.5 {1/self.E:.6g}))"
        return f"{self.E:.6g}" if self.fine == "start" else f"{1/self.E:.6g}"

    def ratio(self, f):
        nh = self.n(f) // (2 if self.twosided else 1)
        return self.E ** (1 / (nh - 1)) if nh > 1 else 1.0

    def dmin(self, f):
        nh = self.n(f) // (2 if self.twosided else 1)
        r = self.ratio(f)
        Lh = self.L / 2 if self.twosided else self.L
        return Lh * (r - 1) / (r ** nh - 1) if r != 1 else Lh / nh


def segments():
    xs = [Seg(-B / 2 - X0, NBASE["xu"], D0, "end"), Seg(B, NBASE["bh"], D0, twosided=True),
          Seg(X3 - B / 2, NBASE["xd"], D0, "start")]
    ys = [Seg(-B / 2 - Y0, NBASE["yl"], D0, "end"), Seg(B, NBASE["bh"], D0, twosided=True),
          Seg(Y3 - B / 2, NBASE["yl"], D0, "start")]
    zs = [Seg(H, NBASE["zh"], D0, twosided=True), Seg(ZT - H, NBASE["za"], D0, "start")]
    return xs, ys, zs


