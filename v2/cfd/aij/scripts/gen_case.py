def foam(path: Path, cls: str, obj: str, body: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HDR.format(cls=cls, obj=obj) + body.strip() + "\n", newline="\n")


HEX_FACES = {"x0": (0, 4, 7, 3), "x1": (1, 2, 6, 5), "y0": (0, 1, 5, 4), "y1": (3, 7, 6, 2),
             "z0": (0, 3, 2, 1), "z1": (4, 5, 6, 7)}


def block_mesh_3d(f: float) -> tuple[str, int, dict]:
    xs, ys, zs = segments()
    xc = [X0, -B / 2, B / 2, X3]
    yc = [Y0, -B / 2, B / 2, Y3]
    zc = [0.0, H, ZT]
    vid = {}
    verts = []
    for k, z in enumerate(zc):
        for j, y in enumerate(yc):
            for i, x in enumerate(xc):
                vid[(i, j, k)] = len(verts)
                verts.append(f"    ({x:.6g} {y:.6g} {z:.6g})  // {len(verts)}")
    blocks, patches, ncells = [], {n: [] for n in ("inlet", "outlet", "sideMin", "sideMax", "top", "ground", "building")}, 0
    for k in range(2):
        for j in range(3):
            for i in range(3):
                if (i, j, k) == (1, 1, 0):
                    continue  # the building
                v = [vid[(i, j, k)], vid[(i + 1, j, k)], vid[(i + 1, j + 1, k)], vid[(i, j + 1, k)],
                     vid[(i, j, k + 1)], vid[(i + 1, j, k + 1)], vid[(i + 1, j + 1, k + 1)], vid[(i, j + 1, k + 1)]]
                nx, ny, nz = xs[i].n(f), ys[j].n(f), zs[k].n(f)
                ncells += nx * ny * nz
                blocks.append(f"    hex ({' '.join(map(str, v))}) ({nx} {ny} {nz})\n"
                              f"        simpleGrading ({xs[i].grading(f)} {ys[j].grading(f)} {zs[k].grading(f)})")

                def face(name):
                    return "(" + " ".join(str(v[q]) for q in HEX_FACES[name]) + ")"
                if i == 0: patches["inlet"].append(face("x0"))
                if i == 2: patches["outlet"].append(face("x1"))
                if j == 0: patches["sideMin"].append(face("y0"))
                if j == 2: patches["sideMax"].append(face("y1"))
                if k == 1: patches["top"].append(face("z1"))
                if k == 0: patches["ground"].append(face("z0"))
                # faces touching the building box
                if k == 0 and j == 1 and i == 0: patches["building"].append(face("x1"))
                if k == 0 and j == 1 and i == 2: patches["building"].append(face("x0"))
                if k == 0 and i == 1 and j == 0: patches["building"].append(face("y1"))
                if k == 0 and i == 1 and j == 2: patches["building"].append(face("y0"))
                if k == 1 and i == 1 and j == 1: patches["building"].append(face("z0"))
    ptype = {"inlet": "patch", "outlet": "patch", "sideMin": "symmetry", "sideMax": "symmetry",
             "top": "patch", "ground": "wall", "building": "wall"}
    bnd = "\n".join(f"    {n}\n    {{\n        type {ptype[n]};\n        faces\n        (\n            "
                    + "\n            ".join(fl) + "\n        );\n    }" for n, fl in patches.items())
    body = (f"scale 1;\n\nvertices\n(\n" + "\n".join(verts) + "\n);\n\nblocks\n(\n" + "\n".join(blocks)
            + "\n);\n\nedges ();\n\nboundary\n(\n" + bnd + "\n);\n")
    info = {"ncells": ncells,
            "n": {"x": sum(s.n(f) for s in xs), "y": sum(s.n(f) for s in ys), "z": sum(s.n(f) for s in zs)},
            "cells_across_b": xs[1].n(f), "cells_0_H": zs[0].n(f),
            "dmin_building_m": xs[1].dmin(f), "dmin_ground_m": zs[0].dmin(f),
            "max_ratio": max(s.ratio(f) for s in xs + ys + zs),
            "domain": {"x": [X0, X3], "y": [Y0, Y3], "z": [0, ZT]},
            "blockage": B * H / ((Y3 - Y0) * ZT)}
    return body, ncells, info


def block_mesh_2d(f: float) -> tuple[str, int, dict]:
    """Empty-domain homogeneity test: same x/z distribution as the 3D mesh, 1 cell in y (2-D, 'empty')."""
    xs, _, zs = segments()
    xc = [X0, -B / 2, B / 2, X3]
    zc = [0.0, H, ZT]
    w = 0.01
    vid, verts = {}, []
    for k, z in enumerate(zc):
        for j, y in enumerate([-w / 2, w / 2]):
            for i, x in enumerate(xc):
                vid[(i, j, k)] = len(verts)
                verts.append(f"    ({x:.6g} {y:.6g} {z:.6g})")
    blocks, patches, ncells = [], {n: [] for n in ("inlet", "outlet", "frontBack", "top", "ground")}, 0
    for k in range(2):
        for i in range(3):
            j = 0
            v = [vid[(i, j, k)], vid[(i + 1, j, k)], vid[(i + 1, j + 1, k)], vid[(i, j + 1, k)],
                 vid[(i, j, k + 1)], vid[(i + 1, j, k + 1)], vid[(i + 1, j + 1, k + 1)], vid[(i, j + 1, k + 1)]]
            nx, nz = xs[i].n(f), zs[k].n(f)
            ncells += nx * nz
            blocks.append(f"    hex ({' '.join(map(str, v))}) ({nx} 1 {nz})\n"
                          f"        simpleGrading ({xs[i].grading(f)} 1 {zs[k].grading(f)})")

            def face(name):
                return "(" + " ".join(str(v[q]) for q in HEX_FACES[name]) + ")"
            if i == 0: patches["inlet"].append(face("x0"))
            if i == 2: patches["outlet"].append(face("x1"))
            patches["frontBack"] += [face("y0"), face("y1")]
            if k == 1: patches["top"].append(face("z1"))
            if k == 0: patches["ground"].append(face("z0"))
    ptype = {"inlet": "patch", "outlet": "patch", "frontBack": "empty", "top": "patch", "ground": "wall"}
    bnd = "\n".join(f"    {n}\n    {{\n        type {ptype[n]};\n        faces\n        (\n            "
                    + "\n            ".join(fl) + "\n        );\n    }" for n, fl in patches.items())
    body = (f"scale 1;\n\nvertices\n(\n" + "\n".join(verts) + "\n);\n\nblocks\n(\n" + "\n".join(blocks)
            + "\n);\n\nedges ();\n\nboundary\n(\n" + bnd + "\n);\n")
    return body, ncells, {"ncells": ncells, "dmin_ground_m": zs[0].dmin(f)}


# ---------------------------------------------------------------- boundary conditions
def turb_var(model: str) -> str:
    return "omega" if model == "kOmegaSST" else "epsilon"


def write_inlet_tables(case: Path):
    t = pd.read_csv(PROC / "inlet_profile.csv")
    c = case / "constant" / "inflow"
    c.mkdir(parents=True, exist_ok=True)
    (c / "U").write_text("(\n" + "\n".join(f"    ({z:.6g} ({u:.6g} 0 0))" for z, u in zip(t.z, t.U)) + "\n)\n", newline="\n")
    for q in ("k", "epsilon", "omega"):
        (c / q).write_text("(\n" + "\n".join(f"    ({z:.6g} {v:.6g})" for z, v in zip(t.z, t[q])) + "\n)\n", newline="\n")


def profile_bc(q: str) -> str:
    return f"""type            fixedProfile;
        profile         tableFile;
        profileCoeffs
        {{
            file            "$FOAM_CASE/constant/inflow/{q}";
            outOfBounds     clamp;
            interpolationScheme linear;
        }}
        direction       (0 0 1);
        origin          0;"""


def abl_common(rh: dict) -> str:
    return f"""flowDir         (1 0 0);
        zDir            (0 0 1);
        Uref            {rh['Uref']:.6g};
        Zref            {rh['Zref']:.6g};
        z0              uniform {rh['z0']:.6g};
        d               uniform 0;
        kappa           {KAPPA};
        Cmu             {CMU};"""


def write_fields(case: Path, kind: str, model: str, inlet: str, ground: str, fits: dict, gwf: str):
    tv = turb_var(model)
    rh = fits["RH_variant"]
    z0g = rh["z0"] if inlet == "loglaw" else Z0_AIJ
    sides = "frontBack" if kind == "empty2d" else "sideMin|sideMax"
    side_bc = "empty" if kind == "empty2d" else "symmetry"
    has_bld = kind == "building"

    def top(q):
        if inlet == "loglaw":   # Richards & Hoxey: impose the inflow values at the top (keeps the shear stress)
            t = {"U": "atmBoundaryLayerInletVelocity", "k": "atmBoundaryLayerInletK",
                 "epsilon": "atmBoundaryLayerInletEpsilon", "omega": "atmBoundaryLayerInletOmega"}[q]
            return f"type {t};\n        {abl_common(rh)}\n        value $internalField;"
        return "type slip;"      # tabulated tunnel profile: top is in the free stream above the BL (zero shear)

    def inl(q):
        if inlet == "loglaw":
            t = {"U": "atmBoundaryLayerInletVelocity", "k": "atmBoundaryLayerInletK",
                 "epsilon": "atmBoundaryLayerInletEpsilon", "omega": "atmBoundaryLayerInletOmega"}[q]
            return f"type {t};\n        {abl_common(rh)}\n        value $internalField;"
        return profile_bc(q) + "\n        value $internalField;"

    bld = lambda s: (f"    building\n    {{\n        {s}\n    }}\n" if has_bld else "")  # noqa: E731
    common_tail = lambda: f"    \"({sides})\"\n    {{\n        type {side_bc};\n    }}\n"  # noqa: E731

    # U
    foam(case / "0" / "U", "volVectorField", "U", f"""
dimensions      [0 1 -1 0 0 0 0];
internalField   uniform (4 0 0);
boundaryField
{{
    inlet
    {{
        {inl('U')}
    }}
    outlet
    {{
        type            inletOutlet;
        inletValue      uniform (0 0 0);
        value           $internalField;
    }}
    top
    {{
        {top('U')}
    }}
    ground
    {{
        type            noSlip;
    }}
{bld('type            noSlip;')}{common_tail()}}}
""")
    # p
    foam(case / "0" / "p", "volScalarField", "p", f"""
dimensions      [0 2 -2 0 0 0 0];
internalField   uniform 0;
boundaryField
{{
    inlet {{ type zeroGradient; }}
    outlet {{ type fixedValue; value uniform 0; }}
    top {{ {'type zeroGradient;' if inlet == 'loglaw' else 'type slip;'} }}
    ground {{ type zeroGradient; }}
{bld('type zeroGradient;')}{common_tail()}}}
""")
    # k
    foam(case / "0" / "k", "volScalarField", "k", f"""
dimensions      [0 2 -2 0 0 0 0];
internalField   uniform 0.5;
boundaryField
{{
    inlet
    {{
        {inl('k')}
    }}
    outlet {{ type zeroGradient; }}
    top
    {{
        {top('k')}
    }}
    ground {{ type kqRWallFunction; value $internalField; }}
{bld('type kqRWallFunction; value $internalField;')}{common_tail()}}}
""")
    # epsilon / omega
    if tv == "epsilon":
        gwall = (f"type atmEpsilonWallFunction; z0 uniform {z0g:.6g}; value $internalField;"
                 if (ground == "rough" and gwf == "atm") else "type epsilonWallFunction; value $internalField;")
        bwall = "type epsilonWallFunction; value $internalField;"
        init = "uniform 1.5"
        dims = "[0 2 -3 0 0 0 0]"
    else:
        gwall = (f"type atmOmegaWallFunction; z0 uniform {z0g:.6g}; value $internalField;"
                 if (ground == "rough" and gwf == "atm") else "type omegaWallFunction; value $internalField;")
        bwall = "type omegaWallFunction; value $internalField;"
        init = "uniform 25"
        dims = "[0 0 -1 0 0 0 0]"
    foam(case / "0" / tv, "volScalarField", tv, f"""
dimensions      {dims};
internalField   {init};
boundaryField
{{
    inlet
    {{
        {inl(tv)}
    }}
    outlet {{ type zeroGradient; }}
    top
    {{
        {top(tv)}
    }}
    ground {{ {gwall} }}
{bld(bwall)}{common_tail()}}}
""")
    # nut
    gnut = (f"type atmNutkWallFunction; z0 uniform {z0g:.6g}; value uniform 0;" if ground == "rough"
            else "type nutkWallFunction; value uniform 0;")
    foam(case / "0" / "nut", "volScalarField", "nut", f"""
dimensions      [0 2 -1 0 0 0 0];
internalField   uniform 0;
boundaryField
{{
    inlet {{ type calculated; value uniform 0; }}
    outlet {{ type calculated; value uniform 0; }}
    top {{ type calculated; value uniform 0; }}
    ground {{ {gnut} }}
{bld('type nutkWallFunction; value uniform 0;')}{common_tail()}}}
""")
    return z0g


# ---------------------------------------------------------------- system files
def schemes(order: int, model: str) -> str:
    tv = turb_var(model)
    if order == 1:
        divU, divT = "bounded Gauss upwind", "bounded Gauss upwind"
    else:
        divU, divT = "bounded Gauss linearUpwind grad(U)", "bounded Gauss limitedLinear 1"
    return f"""
ddtSchemes {{ default steadyState; }}
gradSchemes
{{
    default         Gauss linear;
    grad(U)         cellLimited Gauss linear 1;
    grad(k)         cellLimited Gauss linear 1;
    grad({tv})      cellLimited Gauss linear 1;
}}
divSchemes
{{
    default         none;
    div(phi,U)      {divU};
    div(phi,k)      {divT};
    div(phi,{tv})   {divT};
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}}
laplacianSchemes {{ default Gauss linear corrected; }}
interpolationSchemes {{ default linear; }}
snGradSchemes {{ default corrected; }}
wallDist {{ method meshWave; }}
"""


def fv_solution(model: str, algo: str) -> str:
    tv = turb_var(model)
    if algo == "SIMPLEC":
        simple = "consistent yes;"
        relax = "fields { p 1; }\n    equations { U 0.7; \"(k|epsilon|omega)\" 0.6; }"
    else:
        simple = "consistent no;"
        relax = "fields { p 0.3; }\n    equations { U 0.7; \"(k|epsilon|omega)\" 0.5; }"
    return f"""
solvers
{{
    p
    {{
        solver          GAMG;
        smoother        GaussSeidel;
        tolerance       1e-8;
        relTol          0.05;
    }}
    "(U|k|epsilon|omega)"
    {{
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-9;
        relTol          0.1;
    }}
}}
SIMPLE
{{
    nNonOrthogonalCorrectors 0;
    {simple}
    residualControl
    {{
        p               1e-5;
        U               1e-5;
        "(k|{tv})"      1e-5;
    }}
}}
relaxationFactors
{{
    {relax}
}}
"""


