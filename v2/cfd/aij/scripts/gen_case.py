ALLRUN = r"""#!/bin/bash
# AIJ Case A - {name}. Generated by gen_case.py. Needs an OpenFOAM (ESI v2306+) environment.
# Parallel runs call MS-MPI's mpiexec directly (Windows MinGW build; see E:/PINN/tools/OPENFOAM_SETUP.md).
cd "${{0%/*}}" || exit 1
NP={np}
STAGE1={stage1}
ENDT={endt}
WRITE={write}
rm -f DONE FAILED
fail() {{ echo "FAILED: $1" | tee FAILED; exit 1; }}
run() {{ local log=$1; shift; echo "Running $* ($log)"; "$@" > "$log" 2>&1 || return 1; grep -q "FOAM FATAL" "$log" && return 1; return 0; }}
solve() {{
    if [ "$NP" -gt 1 ]; then run "log.simpleFoam.$1" mpiexec -n $NP simpleFoam -parallel
    else run "log.simpleFoam.$1" simpleFoam; fi
}}
start=$(date +%s)
run log.blockMesh blockMesh || fail blockMesh
run log.checkMesh checkMesh || fail checkMesh
# stage 1: first-order upwind start (robust); written at its last iteration so stage 2 restarts from it
cp -f system/fvSchemes.stage1 system/fvSchemes
foamDictionary -entry endTime -set $STAGE1 system/controlDict > /dev/null
foamDictionary -entry writeInterval -set $STAGE1 system/controlDict > /dev/null
if [ "$NP" -gt 1 ]; then
    foamDictionary -entry numberOfSubdomains -set $NP system/decomposeParDict > /dev/null
    run log.decomposePar decomposePar -force || fail decomposePar
fi
solve stage1 || fail simpleFoam_stage1
# stage 2: second order (linearUpwind for U, limitedLinear for k/eps/omega)
cp -f system/fvSchemes.stage2 system/fvSchemes
if [ "$NP" -gt 1 ]; then for d in processor*; do cp -f system/fvSchemes $d/system/fvSchemes 2>/dev/null; done; fi
foamDictionary -entry endTime -set $ENDT system/controlDict > /dev/null
foamDictionary -entry writeInterval -set $WRITE system/controlDict > /dev/null
solve stage2 || fail simpleFoam_stage2
if [ "$NP" -gt 1 ]; then run log.reconstructPar reconstructPar -latestTime || fail reconstructPar; fi
end=$(date +%s)
echo "wallclock_s $((end-start))" > timing.txt
echo "OK $(date)" > DONE
"""

ALLCLEAN = r"""#!/bin/bash
cd "${0%/*}" || exit 1
. "${WM_PROJECT_DIR:?}/bin/tools/CleanFunctions"
cleanCase0 2>/dev/null || cleanCase
rm -rf processor* postProcessing log.* DONE FAILED timing.txt
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kind", choices=["building", "empty2d"], default="building")
    ap.add_argument("--model", choices=["realizableKE", "kOmegaSST", "kEpsilon"], default="realizableKE")
    ap.add_argument("--inlet", choices=["table", "loglaw"], default="table")
    ap.add_argument("--ground", choices=["rough", "smooth"], default="rough")
    ap.add_argument("--gwf", choices=["atm", "std"], default="atm", help="eps/omega ground wall function")
    ap.add_argument("--level", type=float, default=1.0, help="refinement factor f (1 = medium)")
    ap.add_argument("--algo", choices=["SIMPLEC", "SIMPLE"], default="SIMPLEC")
    ap.add_argument("--np", type=int, default=6)
    ap.add_argument("--stage1", type=int, default=300)
    ap.add_argument("--end", type=int, default=4000)
    ap.add_argument("--write", type=int, default=500)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    case = Path(a.out)
    if case.exists() and any(case.iterdir()):
        raise SystemExit(f"{case} exists and is not empty (use Allclean or a new name)")
    fits = json.loads((PROC / "inflow_fit.json").read_text())
    if a.kind == "building":
        bm, nc, info = block_mesh_3d(a.level)
    else:
        bm, nc, info = block_mesh_2d(a.level)
    foam(case / "system" / "blockMeshDict", "dictionary", "blockMeshDict", bm)
    foam(case / "system" / "controlDict", "dictionary", "controlDict", control_dict(a.kind, a.model, a.end, a.write))
    foam(case / "system" / "fvSchemes.stage1", "dictionary", "fvSchemes", schemes(1, a.model))
    foam(case / "system" / "fvSchemes.stage2", "dictionary", "fvSchemes", schemes(2, a.model))
    foam(case / "system" / "fvSchemes", "dictionary", "fvSchemes", schemes(1, a.model))
    foam(case / "system" / "fvSolution", "dictionary", "fvSolution", fv_solution(a.model, a.algo))
    np_ = a.np if a.kind == "building" else 1
    foam(case / "system" / "decomposeParDict", "dictionary", "decomposeParDict",
         f"numberOfSubdomains {max(np_, 1)};\nmethod scotch;\n")
    foam(case / "constant" / "transportProperties", "dictionary", "transportProperties",
         "transportModel  Newtonian;\nnu              1.5e-05;\n")
    foam(case / "constant" / "turbulenceProperties", "dictionary", "turbulenceProperties",
         f"simulationType RAS;\nRAS\n{{\n    RASModel        {a.model};\n    turbulence      on;\n    printCoeffs     on;\n}}\n")
    write_inlet_tables(case)
    z0g = write_fields(case, a.kind, a.model, a.inlet, a.ground, fits, a.gwf)
    # atmospheric BCs live in libatmosphericModels
    cd = (case / "system" / "controlDict").read_text()
    cd = cd.replace("application     simpleFoam;", "application     simpleFoam;\nlibs            (atmosphericModels);")
    (case / "system" / "controlDict").write_text(cd, newline="\n")
    (case / "Allrun").write_text(ALLRUN.format(name=case.name, np=np_, stage1=a.stage1, endt=a.end, write=a.write), newline="\n")
    (case / "Allclean").write_text(ALLCLEAN, newline="\n")
    meta = {"case": case.name, "kind": a.kind, "model": a.model, "inlet": a.inlet, "ground": a.ground,
            "ground_z0": z0g if a.ground == "rough" else None, "gwf": a.gwf, "level": a.level, "algo": a.algo,
            "np": np_, "stage1": a.stage1, "end": a.end, "mesh": info, "U_H": fits["U_H"], "b": B, "H": H}
    (case / "case.json").write_text(json.dumps(meta, indent=2))
    print(json.dumps(meta, indent=2))


if __name__ == "__main__":
    main()
